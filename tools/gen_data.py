#!/usr/bin/env python3
"""Generate rust/src/data.rs from data/added.json.

added.json: {"versions": [...release names, oldest first...],
             "blocks": {"minecraft:id": "pre-1.0" | version, ...},
             "entities": {...}}
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "data" / "added.json"
src = json.loads(src_path.read_text())
versions = src["versions"]
index = {v: i for i, v in enumerate(versions)}
PRE = 0xFFFF


def table(entries, kind):
    lines = []
    for key in sorted(entries):
        value = entries[key]
        ns, _, path = key.partition(":")
        assert ns == "minecraft", key
        if value == "pre-1.0":
            code = PRE
        elif value in index:
            code = index[value]
        else:
            raise SystemExit(f"{kind} {key}: unknown version {value!r}")
        lines.append(f"{path} {code}")
    return "\n".join(lines)


items_src = src.get("items", {})
blocks = table(src["blocks"], "block")
entities = table(src["entities"], "entity")
items = table(items_src, "item")
(root / "rust" / "src" / "data_blocks.txt").write_text(blocks + "\n")
(root / "rust" / "src" / "data_entities.txt").write_text(entities + "\n")
(root / "rust" / "src" / "data_items.txt").write_text(items + "\n")

out = [
    "//! Generated by tools/gen_data.py from data/added.json. Do not edit.",
    "",
    "/// Java Edition releases from 1.0 onwards, oldest first.",
    "pub static VERSIONS: &[&str] = &[",
]
out += [f'    "{v}",' for v in versions]
out += [
    "];",
    "",
    "/// Version code for things that predate 1.0 (Classic through Beta).",
    f"pub const PRE_RELEASE: u16 = {PRE};",
    "",
    "/// `<block path> <version index>` lines, for `minecraft:` blocks.",
    'pub static BLOCKS: &str = include_str!("data_blocks.txt");',
    "/// `<entity type path> <version index>` lines, for `minecraft:` entities.",
    'pub static ENTITIES: &str = include_str!("data_entities.txt");',
    "/// `<item path> <version index>` lines, for `minecraft:` items.",
    'pub static ITEMS: &str = include_str!("data_items.txt");',
    "",
    f"pub const BLOCK_COUNT: usize = {len(src['blocks'])};",
    f"pub const ENTITY_COUNT: usize = {len(src['entities'])};",
    f"pub const ITEM_COUNT: usize = {len(items_src)};",
    "",
]
(root / "rust" / "src" / "data.rs").write_text("\n".join(out))
print(f"{len(versions)} versions, {len(src['blocks'])} blocks, {len(src['entities'])} entities, {len(items_src)} items")
